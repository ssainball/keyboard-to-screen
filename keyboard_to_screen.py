def show_buffer(data, name=""):
    hex_text = " ".join(f"{byte:02X}" for byte in data)
    print(f"{name:<14} : {hex_text}")


def keyboard_stage(key):
    report = bytearray(8)

    if key.isupper():
        report[0] = LSHIFT

    report[2] = scancode[key.upper()]

    show_buffer(report, "KeyboadBuffer")
    return report


def windows_stage(report):
    show_buffer(report, "WindowsBuffer")
    letter = scancode[report[2]]
    if report[0] & LSHIFT:
        return letter
    else:
        return letter.lower()


def notepad_stage(letter):
    show_buffer(letter.encode("utf-16-le"), "NotepadBuffer")


def graphic_stage(letter):
    bitmap = FONT.get(letter)
    if bitmap is None:
        print("(이 글자의 비트맵은 아직 없습니다)")
        return

    show_buffer(bitmap, "GraphicBuffer")  # VGA 8x16 폰트 데이터 16바이트
    print()

    top = "┌" + "──┬" * 7 + "──┐"  # 픽셀 격자(8칸) 윗줄
    mid = "├" + "──┼" * 7 + "──┤"  # 줄과 줄 사이 경계선
    bottom = "└" + "──┴" * 7 + "──┘"  # 격자 아랫줄

    print("    " + top)
    for y, row in enumerate(bitmap):  # 16줄을 위에서 아래로
        print(f"{y + 1:2d}  │", end="")
        for bit in range(7, -1, -1):  # 왼쪽 비트부터 한 칸씩
            print("██" if (row >> bit) & 1 else "  ", end="│", flush=True)
            time.sleep(0.02)  # 점 하나 찍는 간격
        print(f" {row:02X}")  # 이 줄의 바이트 값
        time.sleep(0.05)  # 한 줄 끝난 뒤 간격
        print("    " + (mid if y < len(bitmap) - 1 else bottom))


while True:
    key = input("\n알파벳 한글자를 입력하세요 > ")

    if key == "0":
        print("종료합니다")
        break

    if len(key) != 1 or not (key.isascii() and key.isalpha()):
        print("알파벳 한글자를 입력하셔야 합니다.")
        continue

    report = keyboard_stage(key)
    letter = windows_stage(report)
    notepad_stage(letter)
    graphic_stage(letter)
