def show_buffer(data):
    hex_text = " ".join(f"{byte:02X}" for byte in data)
    print(hex_text)


def keyboard_stage(key):
    report = bytearray(8)

    if key.isupper():
        report[0] = LSHIFT

    report[2] = scancode[key.upper()]

    show_buffer(report)
    return report


def windows_stage(report):
    show_buffer(report)
    letter = scancode[report[2]]
    if report[0] & LSHIFT:
        return letter
    else:
        return letter.lower()


def notepad_stage(letter):
    show_buffer(letter.encode("utf-16-le"))


def graphic_stage(letter):
    bitmap = FONT.get(letter)
    if bitmap is None:
        print("(이 글자의 비트맵은 아직 없습니다)")
        return

    show_buffer(bitmap)  # 폰트 데이터 8바이트
    print()

    for row in bitmap:  # 한 줄씩 천천히 그리기
        for bit in range(7, -1, -1):  # 왼쪽 비트부터 한 점씩
            print("██" if (row >> bit) & 1 else "  ", end="", flush=True)
            time.sleep(0.03)  # 점 하나 찍는 간격
        print()
        time.sleep(0.2)  # 한 줄 끝난 뒤 간격


